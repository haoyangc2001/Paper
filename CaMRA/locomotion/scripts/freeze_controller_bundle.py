"""Freeze the validated Go2 velocity controller into a versioned, read-only bundle.

TASK-027. The candidate directory produced by ``export_policy_candidate.py`` holds the
artefacts but lives next to the training run and can be regenerated by accident. This
script turns it into a *frozen* release: a new, never-reused version directory that
carries everything needed to reload the controller without the training directory,
one hash per file, a tree digest over the whole bundle, and the provenance that makes
the numbers in TASK-024 / TASK-026 reproducible.

Rules baked into the script, not into prose:

* an existing version directory is never touched -- the only way forward is a new
  version name, which by the versioning rule forces a re-verify and a re-calibration;
* every file is copied, never referenced, so deleting the run directory cannot break
  the bundle (the Go2 asset tree is copied for the same reason);
* the manifest records a digest of every file *plus* a digest of the digest list, so a
  single swapped file is detectable and so is a whole-file-set swap;
* the manifest itself is hashed into ``frozen_manifest.json.sha256`` and then the whole
  tree is made read-only, so "frozen" is a file-system fact rather than a promise.

Nothing here needs Isaac: the manifest is assembled from the candidate's contract
files plus the interpreter's own version table.
"""

