def pip_freeze(path: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    proc = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(proc.stdout)


def git_info(repo: str) -> dict:
    def run(*args: str) -> str:
        return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True).stdout.strip()

    # dirty must cover untracked files too: `git diff` cannot see them, and a bundle whose
    # own scripts were never committed would otherwise claim a clean provenance
    status = subprocess.run(
        ["git", "-C", repo, "status", "--porcelain", "--untracked-files=normal", "--", "CaMRA/locomotion"],
        capture_output=True, text=True,
    ).stdout.strip().splitlines()
    noise = ("__pycache__/", ".pyc", ".bak")
    relevant = []
    for line in status:
        if not line.strip() or any(n in line for n in noise):
            continue
        # porcelain is "XY<space>path"; slicing at 2 keeps the separator-space handling
        # out of the way (a staged "M " and an unstaged " M" both parse correctly)
        path = line[2:].strip()
        if "->" in path:  # rename entries
            path = path.split("->")[-1].strip()
        if line[:2].strip() and line[:2].strip() != "??":
            # `git status` reports stat-dirty files whose content is identical (this repo
            # carries `<text: auto>` attributes and CRLF churn), so a tracked entry only
            # counts when the content actually differs from HEAD
            if subprocess.run(
                ["git", "-C", repo, "diff", "--quiet", "HEAD", "--", path],
                capture_output=True, text=True,
            ).returncode == 0:
                continue
        relevant.append(line)
    info = {
        "repo": repo,
        "commit": run("rev-parse", "HEAD"),
        "branch": run("rev-parse", "--abbrev-ref", "HEAD"),
        "dirty_scope": "CaMRA/locomotion, tracked *and* untracked (git status --porcelain, "
                       "__pycache__/*.pyc/*.bak filtered out)",
        "dirty": bool(relevant),
        "dirty_entries": relevant[:40],
        "tracked_paths_in_bundle": sorted(
            p for p in BUNDLE_SCRIPTS if p.startswith("scripts/")
        ),
    }
    for sub in ("HiRA",):
        p = os.path.join(repo, sub)
        if os.path.isdir(p):
            info[f"submodule_{sub}"] = subprocess.run(
                ["git", "-C", p, "rev-parse", "HEAD"], capture_output=True, text=True
            ).stdout.strip()
    return info


