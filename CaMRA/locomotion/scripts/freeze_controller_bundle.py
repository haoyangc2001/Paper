def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tree_integrity(root: str) -> tuple[dict[str, dict], str]:
    """Hash every regular file under root; return (per-file table, tree digest)."""
    files: dict[str, dict] = {}
    for base, _dirs, names in os.walk(root):
        for name in sorted(names):
            if name.endswith(".sha256") or name == "frozen_manifest.json":
                continue  # verified separately, would be self-referential
            full = os.path.join(base, name)
            if os.path.islink(full) or not os.path.isfile(full):
                continue
            rel = os.path.relpath(full, root)
            files[rel] = {"sha256": sha256_file(full), "bytes": os.path.getsize(full)}
    lines = "\n".join(f"{rel} {meta['sha256']} {meta['bytes']}" for rel, meta in sorted(files.items()))
    return files, hashlib.sha256(lines.encode()).hexdigest()


